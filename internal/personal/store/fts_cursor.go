package store

import (
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"errors"
	"fmt"
	"hash"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const (
	searchCursorVersion     = "v1"
	maxSearchSnapshotHits   = 500
	searchCursorRestartNote = "cursor ignored; starting from beginning"
)

var errInvalidSearchCursor = errors.New("invalid search cursor")

// searchCursor is deliberately only a snapshot position. Query conditions and
// result ordering stay in the in-process snapshot owned by the store.
type searchCursor struct {
	SnapshotID string
	Offset     int
}

// encodeSearchCursor creates the stable, human-readable cursor format used by
// session_search. The snapshot limit also bounds offsets before a snapshot
// lookup is attempted.
func encodeSearchCursor(cursor searchCursor) (string, error) {
	if err := validateSearchSnapshotID(cursor.SnapshotID); err != nil {
		return "", err
	}
	if err := validateSearchCursorOffset(cursor.Offset); err != nil {
		return "", err
	}
	return fmt.Sprintf("%s.%s.%d", searchCursorVersion, cursor.SnapshotID, cursor.Offset), nil
}

// decodeSearchCursor rejects anything outside the versioned, three-field
// format. In particular, it never returns a partially decoded cursor that a
// caller could accidentally use as a SQL value.
func decodeSearchCursor(raw string) (searchCursor, error) {
	parts := strings.Split(raw, ".")
	if len(parts) != 3 || parts[0] != searchCursorVersion {
		return searchCursor{}, errInvalidSearchCursor
	}
	if err := validateSearchSnapshotID(parts[1]); err != nil {
		return searchCursor{}, errInvalidSearchCursor
	}
	if err := validateSearchCursorOffsetText(parts[2]); err != nil {
		return searchCursor{}, errInvalidSearchCursor
	}
	offset, err := strconv.Atoi(parts[2])
	if err != nil {
		return searchCursor{}, errInvalidSearchCursor
	}
	return searchCursor{SnapshotID: parts[1], Offset: offset}, nil
}

// parseSearchCursor converts untrusted input into either a valid position or a
// restart note. The snapshot layer will separately report an expired or
// evicted snapshot; malformed input must not fail the underlying search.
func parseSearchCursor(raw string) (searchCursor, string) {
	if raw == "" {
		return searchCursor{}, ""
	}
	cursor, err := decodeSearchCursor(raw)
	if err != nil {
		return searchCursor{}, searchCursorRestartNote
	}
	return cursor, ""
}

// validateSearchSnapshotID keeps the identifier a single safe cursor field;
// snapshot IDs generated by the cache use this ASCII alphabet.
func validateSearchSnapshotID(id string) error {
	if id == "" {
		return errInvalidSearchCursor
	}
	for _, r := range id {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') ||
			(r >= '0' && r <= '9') || r == '_' || r == '-' {
			continue
		}
		return errInvalidSearchCursor
	}
	return nil
}

// validateSearchCursorOffset enforces the maximum position representable by a
// bounded search snapshot; the snapshot layer still checks its actual length.
func validateSearchCursorOffset(offset int) error {
	if offset < 0 || offset > maxSearchSnapshotHits {
		return errInvalidSearchCursor
	}
	return nil
}

func validateSearchCursorOffsetText(raw string) error {
	if raw == "" || (len(raw) > 1 && raw[0] == '0') {
		return errInvalidSearchCursor
	}
	for _, r := range raw {
		if r < '0' || r > '9' {
			return errInvalidSearchCursor
		}
	}
	if _, err := strconv.ParseUint(raw, 10, 0); err != nil {
		return errInvalidSearchCursor
	}
	offset, err := strconv.Atoi(raw)
	if err != nil {
		return errInvalidSearchCursor
	}
	return validateSearchCursorOffset(offset)
}

// searchFingerprint is a digest of every EntrySearch condition that changes
// the result set. It is suitable as an in-memory map key and never exposes the
// query or paths in a cursor.
type searchFingerprint string

// fingerprintEntrySearch canonicalizes semantically equivalent conditions
// before hashing. Absolute timestamp formatting and path normalization must
// match the SQL builder, otherwise a relative-time query could reuse a stale
// snapshot or equivalent kind lists could create needless snapshots.
func fingerprintEntrySearch(q EntrySearch) (searchFingerprint, error) {
	kinds, err := canonicalSearchKinds(q.Kinds)
	if err != nil {
		return "", err
	}

	h := sha256.New()
	writeFingerprintField(h, "version", searchCursorVersion)
	writeFingerprintField(h, "query", strings.Join(strings.Fields(q.Query), " "))
	writeFingerprintField(h, "scope", searchScope(q))
	writeFingerprintField(h, "current", q.CurrentSessionID)
	writeFingerprintField(h, "workspace", normalizeSearchWorkspace(q.WorkspaceDir, q.FoldCase))
	writeFingerprintField(h, "fold_case", strconv.FormatBool(q.FoldCase))
	writeFingerprintField(h, "include_agents", strconv.FormatBool(q.IncludeAgents))
	writeFingerprintField(h, "since", formatTime(q.Since))
	writeFingerprintField(h, "until", formatTime(q.Until))
	writeFingerprintField(h, "cwd_prefix", q.CWDPrefix)
	// Written only when it excludes something, so a search without the option
	// keeps the fingerprint it had before the option existed.
	if ex := q.ExcludeSession.normalized(); ex.active() {
		writeFingerprintField(h, "exclude_session", ex.SessionID)
		for _, r := range ex.Ranges {
			writeFingerprintField(h, "exclude_range", strconv.FormatInt(r.Lo, 10)+":"+strconv.FormatInt(r.Hi, 10))
		}
	}
	for _, id := range canonicalSearchStrings(q.SessionIDs) {
		writeFingerprintField(h, "session_id", id)
	}
	for _, kind := range kinds {
		writeFingerprintField(h, "kind", kind)
	}
	return searchFingerprint(hex.EncodeToString(h.Sum(nil))), nil
}

func writeFingerprintField(h hash.Hash, name, value string) {
	writeFingerprintPart(h, name)
	writeFingerprintPart(h, value)
}

// Length-prefixing each field prevents concatenation ambiguities when query
// text or paths contain bytes that also occur in field names or values.
func writeFingerprintPart(h hash.Hash, value string) {
	var length [8]byte
	binary.BigEndian.PutUint64(length[:], uint64(len(value)))
	_, _ = h.Write(length[:])
	_, _ = h.Write([]byte(value))
}

// searchScope derives the three public scope modes from the store-level fields
// used by the SQL builder: workspace also carries the current-session branch.
func searchScope(q EntrySearch) string {
	switch {
	case q.WorkspaceDir != "":
		return "workspace"
	case q.CurrentSessionID != "":
		return "current"
	default:
		return "all"
	}
}

// normalizeSearchWorkspace mirrors workspaceScopeCondition's filepath.Clean
// and approved ASCII-only case folding without applying Unicode case changes
// that SQLite lower() will not apply.
func normalizeSearchWorkspace(workspace string, foldCase bool) string {
	if workspace == "" {
		return ""
	}
	workspace = filepath.Clean(workspace)
	if foldCase {
		workspace = foldASCII(workspace)
	}
	return workspace
}

func foldASCII(value string) string {
	return strings.Map(func(r rune) rune {
		if r >= 'A' && r <= 'Z' {
			return r + ('a' - 'A')
		}
		return r
	}, value)
}

// canonicalSearchKinds makes the IN-list order and duplicate spelling
// irrelevant to the fingerprint while retaining the store's validation rule.
func canonicalSearchKinds(kinds []string) ([]string, error) {
	if err := validateSearchKinds(kinds); err != nil {
		return nil, err
	}
	if len(kinds) == 0 {
		return nil, nil
	}
	allowed := []string{EntryUser, EntryAssistant, EntryTool, EntryCompaction, EntryHandoff}
	present := make(map[string]bool, len(kinds))
	for _, kind := range kinds {
		present[kind] = true
	}
	out := make([]string, 0, len(present))
	for _, kind := range allowed {
		if present[kind] {
			out = append(out, kind)
		}
	}
	return out, nil
}

// canonicalSearchStrings sorts and deduplicates order-insensitive SQL IN-list
// values without mutating the caller's slice.
func canonicalSearchStrings(values []string) []string {
	if len(values) == 0 {
		return nil
	}
	out := append([]string(nil), values...)
	sort.Strings(out)
	unique := out[:0]
	for _, value := range out {
		if len(unique) == 0 || unique[len(unique)-1] != value {
			unique = append(unique, value)
		}
	}
	return unique
}
